import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { buildCronActivitySeries } from './activity-aggregation'
import { parseScheduleCron } from './parse-schedule-cron'
import { getMinCronIntervalMs, getNextCronTime, validateScheduleExpression } from './schedule-parser'

const start = '2026-02-10T12:00:00.000Z'

beforeEach(() => {
  vi.useFakeTimers()
  vi.setSystemTime(new Date(start))
})
afterEach(() => vi.useRealTimers())

describe('stored cron expressions with redundant zero values', () => {
  // Fixed UTC instants from 5.5.0. These same fixtures are also run against the
  // old package in upgrade validation; no expected date is generated by 5.10.
  it.each([
    {
      expression: '0,0 9 * * *',
      expected: ['2026-02-11T09:00:00.000Z', '2026-02-12T09:00:00.000Z'],
    },
    {
      expression: '0,0 15 9 * * *',
      expected: ['2026-02-11T09:15:00.000Z', '2026-02-12T09:15:00.000Z'],
    },
    {
      expression: '0 9 * * 0,7',
      expected: ['2026-02-15T09:00:00.000Z', '2026-02-22T09:00:00.000Z'],
    },
    {
      expression: '0 9 * * SUN,7',
      expected: ['2026-02-15T09:00:00.000Z', '2026-02-22T09:00:00.000Z'],
    },
    {
      expression: '0,0 0,0 0,0 * * SUN,7',
      expected: ['2026-02-15T00:00:00.000Z', '2026-02-22T00:00:00.000Z'],
    },
    {
      expression: '0-2,0 9 * * *',
      expected: ['2026-02-11T09:00:00.000Z', '2026-02-11T09:01:00.000Z', '2026-02-11T09:02:00.000Z'],
    },
    {
      expression: '0,0,1,1 9 * * *',
      expected: ['2026-02-11T09:00:00.000Z', '2026-02-11T09:01:00.000Z', '2026-02-12T09:00:00.000Z'],
    },
    {
      expression: '0 9 11 * 0,7',
      expected: ['2026-02-11T09:00:00.000Z', '2026-02-15T09:00:00.000Z', '2026-02-22T09:00:00.000Z'],
    },
    {
      expression: '0 9 1 * 0-6,7',
      expected: ['2026-02-11T09:00:00.000Z', '2026-02-12T09:00:00.000Z'],
    },
    {
      expression: '0 9 1 * *,0',
      expected: ['2026-02-11T09:00:00.000Z', '2026-02-12T09:00:00.000Z'],
    },
    {
      expression: '0,0 9 1 * *',
      expected: ['2026-03-01T09:00:00.000Z', '2026-04-01T09:00:00.000Z'],
    },
    {
      expression: '0,0 9 * * THU',
      expected: ['2026-02-12T09:00:00.000Z', '2026-02-19T09:00:00.000Z'],
    },
    {
      expression: '0 9 * * 0,0,5L',
      expected: ['2026-02-15T09:00:00.000Z', '2026-02-22T09:00:00.000Z', '2026-02-27T09:00:00.000Z'],
    },
    {
      expression: '0 9 * * 0,0,1L,1L',
      expected: ['2026-02-15T09:00:00.000Z', '2026-02-22T09:00:00.000Z', '2026-02-23T09:00:00.000Z'],
    },
    {
      expression: '0 9 * * 0,0,7L,7L',
      expected: ['2026-02-15T09:00:00.000Z', '2026-02-22T09:00:00.000Z', '2026-03-01T09:00:00.000Z'],
    },
  ])('preserves scheduling and recorded history for $expression', ({ expression, expected }) => {
    expect(validateScheduleExpression('cron', expression, 'UTC').valid).toBe(true)
    for (const timestamp of expected) {
      const next = getNextCronTime(expression, 'UTC')
      expect(next.toISOString()).toBe(timestamp)
      vi.setSystemTime(next)
    }
    const sessions = expected.map((scheduledExecutionAt, index) => ({
      scheduledExecutionAt,
      automationStatus: index === 0 ? 'failed' as const : 'succeeded' as const,
    }))
    expect(buildCronActivitySeries({
      task: { id: 'stored-expression', scheduleExpression: expression, timezone: 'UTC', createdAt: new Date(start) },
      sessions,
      now: new Date(Date.now() + 60_001),
      slots: expected.length,
    })).toEqual(sessions.map(({ scheduledExecutionAt, automationStatus }) => ({
      scheduledAt: scheduledExecutionAt,
      status: automationStatus,
    })))
  })

  it('measures frequency from the same compatible expression used for execution', () => {
    expect(getMinCronIntervalMs('0,0,5 * * * *', 'UTC')).toBe(5 * 60_000)
  })

  it.each([
    '1,1 9 * * *', // No duplicate zero: do not relax upstream validation.
    '0,0 9,9 * * *', // A different field is still invalid after repairing minutes.
    '0,,0 9 * * *',
    '0,0,90 9 * * *',
    '0 9 * * 0,0#2',
    '0,0 9 * * h', // Lowercase h is invalid upstream, not a hash alias.
  ])('still rejects malformed or unsupported fields in %s', (expression) => {
    expect(validateScheduleExpression('cron', expression, 'UTC').valid).toBe(false)
  })

  it('keeps the original expression length limit before any deduplication', () => {
    expect(validateScheduleExpression('cron', `${'0,'.repeat(600)}0 9 * * *`).error).toMatch(/too long/i)
  })

  it('keeps the original field expansion limit before any deduplication', () => {
    expect(validateScheduleExpression('cron', `${'0,'.repeat(300)}0 9 * * *`).error).toMatch(/too many values/i)
  })

  it.each([
    `${Array<string>(257).fill('0').join(',')} 9 * * *`,
    '0-59,0-59,0-59,0-59,0-59 9 * * *',
  ])('rejects a final atom that takes %s beyond the field expansion limit', (expression) => {
    expect(validateScheduleExpression('cron', expression).error).toMatch(/too many values/i)
  })

  it('does not retry a duplicate-zero expression containing a hashed field', () => {
    expect(() => parseScheduleCron('0,0 H * * *')).toThrow(/duplicate values found: 0/)
    // An otherwise-valid hash still follows the upstream path, including its seed.
    const parsed = parseScheduleCron('H * * * *', { hashSeed: 'stored-task', currentDate: start, tz: 'UTC' })
    expect(parsed.next().getTime()).toBeGreaterThan(new Date(start).getTime())
  })
})
