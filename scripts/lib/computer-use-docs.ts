/** A command's positional argument, as a tool param. */
export interface ToolArgument {
  /** The param: the help's placeholder in lower case (`<REF>` → `ref`). */
  name: string
  required: boolean
  description: string
}

/** A command's flag, as a tool param. */
export interface ToolOption {
  flag: string
  /** The param: the flag in snake case (`--wait-for` → `wait_for`). */
  name: string
  /** A switch takes no value; a list repeats the flag once per value. */
  kind: 'switch' | 'value' | 'list'
  required: boolean
  values?: string[]
  /**
   * The values one OS takes, where agent-desktop's `status` there names fewer
   * than `values` (its help lists every OS's surfaces): `{ macos: [...] }`.
   */
  platformValues?: Record<string, string[]>
  description: string
}

/** One agent-desktop command as a tool: generated from its `--help`, so the tool is the command. */
export interface ToolSpec {
  command: string
  tool: string
  description: string
  arguments: ToolArgument[]
  options: ToolOption[]
}

/** The lines of a help section (`Arguments:`, `Options:`), up to the blank line that ends it. */
function helpSection(lines: readonly string[], title: string): string[] {
  const start = lines.findIndex((line) => line.trim() === title)
  if (start === -1) return []
  const section: string[] = []
  for (const line of lines.slice(start + 1)) {
    if (!line.trim()) break
    section.push(line)
  }
  return section
}

const OPTION_LINE = /^\s+(?:-[A-Za-z], )?(--[a-z0-9-]+)(?: (\[?<[^>]+>\]?))?(?:\s{2,}(.*))?$/
const ARGUMENT_LINE = /^\s+[<[]([A-Z][A-Z0-9_]*)[>\]](?:\.\.\.)?\s{2,}(.*)$/

/** A command's tool, from its `--help`. */
export function parseToolSpec(command: string, help: string): ToolSpec {
  const lines = filterHelp(help).split('\n')
  const blank = lines.findIndex((line) => !line.trim())
  const description = lines.slice(0, blank === -1 ? 1 : blank).join(' ').trim()
  const usage = lines.find((line) => line.startsWith('Usage: ')) ?? ''
  const omitted = new Set(REFUSED_FLAGS[command] ?? [])

  // Positionals and required flags from the usage line: `<REF>` is required,
  // `[REF]` optional, and `--xy <XY>` a flag the command cannot do without.
  const usageTokens = usage.replace(/^Usage: \S+ \S+/, '').trim().split(/\s+/).filter(Boolean)
  const positionals: Array<{ placeholder: string; required: boolean }> = []
  const requiredFlags = new Set<string>()
  for (let i = 0; i < usageTokens.length; i++) {
    const token = usageTokens[i]
    if (token === '[OPTIONS]') continue
    if (token.startsWith('--')) {
      requiredFlags.add(token)
      i++
      continue
    }
    const match = /^([<[])([A-Z][A-Z0-9_]*)[>\]](?:\.\.\.)?$/.exec(token)
    if (match) positionals.push({ placeholder: match[2], required: match[1] === '<' })
  }
  const argumentDescriptions = new Map(helpSection(lines, 'Arguments:').flatMap((line) => {
    const match = ARGUMENT_LINE.exec(line)
    return match ? [[match[1], match[2].trim()] as const] : []
  }))
  const args: ToolArgument[] = positionals
    .filter(({ placeholder }) => !omitted.has(placeholder))
    .map(({ placeholder, required }) => ({
      name: placeholder.toLowerCase(),
      required,
      description: argumentDescriptions.get(placeholder) ?? '',
    }))

  // The global wait flags say where they apply (snapshot and ref actions); a
  // tool carries them only there, and on press, which agent-desktop's guide
  // pairs with --wait-for though its help marks them for snapshot and ref
  // actions only.
  const takesWaitFlags = command === 'snapshot' || command === 'press' || args.some((arg) => arg.name === 'ref')
  const options: ToolOption[] = []
  for (const line of helpSection(lines, 'Options:')) {
    const match = OPTION_LINE.exec(line)
    if (!match || omitted.has(match[1])) continue
    const [, flag, placeholder, rest = ''] = match
    if (!takesWaitFlags && (/\(snapshot and ref actions only\)/.test(rest) || flag === '--wait-timeout')) continue
    const values = /\[possible values: ([^\]]+)\]/.exec(rest)?.[1].split(',').map((value) => value.trim())
    const kind = !placeholder ? 'switch' : /\brepeatable\b/i.test(rest) ? 'list' : 'value'
    options.push({
      flag,
      name: flag.slice(2).replace(/-/g, '_'),
      kind,
      required: requiredFlags.has(flag),
      ...(values && { values }),
      description: rest.replace(/\s*\[possible values: [^\]]+\]/, '').trim(),
    })
  }
  const names = [...args.map((arg) => arg.name), ...options.map((option) => option.name)]
  const clash = names.find((name, i) => names.indexOf(name) !== i)
  if (clash) throw new Error(`agent-desktop ${command}: the argument and the flag both become the param "${clash}"`)
  return { command, tool: toolName(command), description, arguments: args, options }
}

/**
 * The tools with each `--surface` narrowed, for one OS, to the surfaces
 * agent-desktop's `status` reports there (`supported_surfaces`): the help
 * offers every OS's, and one from another OS is refused as INVALID_ARGS. A
 * binary only knows its own OS, so the other OSes' narrowing is carried over
 * from `previous` (the specs generated before, possibly on another OS).
 */
export function withPlatformSurfaces(
  specs: readonly ToolSpec[],
  platform: string,
  supported: readonly string[],
  previous: readonly ToolSpec[] = [],
): ToolSpec[] {
  return specs.map((spec) => ({
    ...spec,
    options: spec.options.map((option) => {
      if (option.flag !== '--surface' || !option.values) return option
      const before = previous.find((p) => p.command === spec.command)?.options.find((o) => o.flag === option.flag)?.platformValues
      const platformValues: Record<string, string[]> = {}
      for (const [os, values] of Object.entries(before ?? {})) {
        if (os !== platform) platformValues[os] = values.filter((value) => option.values!.includes(value))
      }
      const values = option.values.filter((value) => supported.includes(value))
      if (values.length < option.values.length) platformValues[platform] = values
      const { platformValues: _ignored, ...rest } = option
      return Object.keys(platformValues).length > 0 ? { ...rest, platformValues } : rest
    }),
  }))
}

