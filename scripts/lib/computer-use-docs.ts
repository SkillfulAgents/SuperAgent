/**
 * The agent-facing computer-use guides, built from the skills agent-desktop
 * ships for its own version.
 *
 * agent-desktop's skills describe its command line, and agents here run the
 * same commands: `computer_<command>` tools generated from each command's
 * `--help` (renderToolSpecs), and `agent_desktop({ args })` for any command.
 * Each guide is the upstream markdown as is, with only its "load this skill"
 * pointers turned into paths under `/opt/gamut/docs/computer-use/`; the main
 * guide opens with a short Gamut header on what the app sets and refuses.
 *
 * Pure: reading the skills and writing files is the generator's
 * (scripts/generate-computer-use-docs.ts).
 */

/** Where the guides are installed in the agent container. */
export const DOCS_ROOT = '/opt/gamut/docs'
export const GUIDE_DIR = `${DOCS_ROOT}/computer-use`

/** One upstream skill the guides are built from. */
export interface SkillSpec {
  /** The skill's directory under `skills/` in the agent-desktop repo. */
  dir: string
  /** The name `agent-desktop skills get` takes. */
  alias: string
  /** Prefix of its reference files in GUIDE_DIR: none for the core skill. */
  prefix: string
  /** The file the skill itself becomes, relative to DOCS_ROOT. Null for the core skill, which the main guide embeds. */
  file: string | null
}

export const CORE_SKILL: SkillSpec = { dir: 'agent-desktop', alias: 'desktop', prefix: '', file: null }

export const PLATFORM_SKILLS: readonly SkillSpec[] = [
  { dir: 'agent-desktop-macos', alias: 'macos', prefix: 'macos-', file: 'computer-use/macos.md' },
  { dir: 'agent-desktop-windows', alias: 'windows', prefix: 'windows-', file: 'computer-use/windows.md' },
]

const STAMP_PREFIX = '<!-- generated by scripts/generate-computer-use-docs.ts from agent-desktop '

/** The first line of every generated guide: which agent-desktop version it describes. */
export function versionStamp(version: string): string {
  return `${STAMP_PREFIX}${version}; do not edit -->`
}

/** The agent-desktop version a generated guide was built from, or null when it has no stamp. */
export function readVersionStamp(markdown: string): string | null {
  const first = markdown.split('\n', 1)[0] ?? ''
  if (!first.startsWith(STAMP_PREFIX)) return null
  const rest = first.slice(STAMP_PREFIX.length)
  const end = rest.indexOf(';')
  return end === -1 ? null : rest.slice(0, end)
}

/** Drop a leading YAML frontmatter block (the repo's SKILL.md files carry one). */
export function stripFrontmatter(markdown: string): string {
  if (!markdown.startsWith('---\n')) return markdown
  const end = markdown.indexOf('\n---\n', 4)
  return end === -1 ? markdown : markdown.slice(end + 5).replace(/^\n+/, '')
}

/** The reference name in a skill listing entry: `references/commands-system.md` → `commands-system`. */
export function referenceName(entry: string): string {
  return entry.replace(/^references\//, '').replace(/\.md$/, '')
}

/** A reference's file in GUIDE_DIR. */
export function referencePath(skill: SkillSpec, reference: string): string {
  return `${GUIDE_DIR}/${skill.prefix}${reference}.md`
}

/**
 * Turn the skill's own pointers into guide paths:
 * - `agent-desktop skills get desktop <reference>` → that reference's file
 * - `agent-desktop skills get desktop` → the main guide
 * - `agent-desktop skills get platform` / `macos` / `windows` → the platform guides
 * - `references/x.md` links → the skill's reference file
 * - a bare core reference file name (`commands-system.md`) → its file
 */
export function rewriteSkillLinks(
  markdown: string,
  skill: SkillSpec,
  coreReferences: readonly string[],
): string {
  const platformGuides = PLATFORM_SKILLS.map((platform) => `${DOCS_ROOT}/${platform.file}`).join('` or `')
  let out = markdown
    // A skill is read, not run, once it is a file.
    .replace(/\b([Rr])un `agent-desktop skills get/g, '$1ead `agent-desktop skills get')
    .replace(/agent-desktop skills get desktop <reference>/g, `${GUIDE_DIR}/<reference>.md`)
    .replace(/agent-desktop skills get (?:desktop|agent-desktop) ([a-z][\w-]*)/g, (_m, ref: string) => referencePath(CORE_SKILL, ref))
    .replace(/agent-desktop skills get (?:desktop|agent-desktop)\b/g, `${DOCS_ROOT}/computer-use.md`)
    .replace(/agent-desktop skills get platform\b/g, platformGuides)
  for (const platform of PLATFORM_SKILLS) {
    out = out.replace(new RegExp(`agent-desktop skills get ${platform.alias} ([a-z][\\w-]*)`, 'g'), (_m, ref: string) => referencePath(platform, ref))
    out = out.replace(new RegExp(`agent-desktop skills get ${platform.alias}\\b`, 'g'), `${DOCS_ROOT}/${platform.file}`)
  }
  out = out.replace(/(?<![\w/.-])references\/([\w-]+)\.md/g, (_m, ref: string) => referencePath(skill, ref))
  if (coreReferences.length > 0) {
    const names = coreReferences.map((name) => name.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')).join('|')
    out = out.replace(new RegExp(`(?<![\\w/.-])(${names})\\.md`, 'g'), (_m, ref: string) => referencePath(CORE_SKILL, ref))
  }
  return out
}

