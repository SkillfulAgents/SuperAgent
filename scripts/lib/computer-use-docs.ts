/** The markdown without the `## ` sections titled `titles`, each up to the next heading of its level or above. */
export function dropSections(markdown: string, titles: readonly string[]): string {
  const lines = markdown.split('\n')
  const out: string[] = []
  let dropping = false
  for (const line of lines) {
    const heading = /^(#{1,2}) (.+)$/.exec(line)
    if (heading) dropping = heading[1] === '##' && titles.includes(heading[2].trim())
    if (!dropping) out.push(line)
  }
  return out.join('\n')
}

/**
 * The markdown without the lines matching `patterns`. An ordered list that
 * loses an item is numbered again, up to the end of the list.
 */
export function dropLines(markdown: string, patterns: readonly RegExp[]): string {
  const out: string[] = []
  let dropped = 0
  for (const line of markdown.split('\n')) {
    const item = /^(\d+)\. /.exec(line)
    // A blank or unindented line that is not an item ends the list.
    if (!item && !/^\s+\S/.test(line)) dropped = 0
    if (patterns.some((pattern) => pattern.test(line))) {
      if (item) dropped++
      continue
    }
    out.push(item && dropped > 0 ? line.replace(/^\d+/, String(Number(item[1]) - dropped)) : line)
  }
  return out.join('\n')
}

/** Commands the app runs itself (the session, its cursor, traces, the OS permissions), left out of the flags guide. */
export const REFUSED_COMMANDS: ReadonlySet<string> = new Set(['session', 'trace', 'cursor-overlay', 'permissions', 'help'])

/** Global flags the app sets on every call (or refuses), left out of the flags guide and the tools. */
const HOST_OWNED_FLAGS = [
  '--session', '--agent-id', '--trace', '--trace-strict', '--screenshot', '--debug', '--help', '--version',
  // Logs to stderr, which no agent reads.
  '--verbose',
]

const HOST_OWNED_FLAG_LINE = new RegExp(`^\\s+(?:-\\w, )?(?:${HOST_OWNED_FLAGS.join('|')})(?:[\\s<=]|$)`)

/** The command names in `agent-desktop --help`'s Commands section. */
export function parseCommandList(help: string): string[] {
  const lines = help.split('\n')
  const start = lines.findIndex((line) => line.trim() === 'Commands:')
  if (start === -1) return []
  const commands: string[] = []
  for (const line of lines.slice(start + 1)) {
    const match = /^ {2}([a-z][a-z0-9-]*)\s/.exec(line)
    if (!match) break
    commands.push(match[1])
  }
  return commands
}

/** A command's help without the lines for flags the app sets itself. */
export function filterHelp(help: string): string {
  return help.split('\n').filter((line) => !HOST_OWNED_FLAG_LINE.test(line)).join('\n').trim()
}

/**
 * The flags guide: each command agents may run, with its help. A command's
 * own section leaves out the options every command takes (listed once, at the
 * top) and the flags the app refuses on it.
 */
export function renderFlagsGuide(version: string, globalHelp: string, commands: ReadonlyArray<{ command: string; help: string }>): string {
  // Only the Options block: the long help after it repeats the core guide.
  const options = globalHelp.slice(Math.max(0, globalHelp.indexOf('Options:')))
  const end = options.indexOf('\n\n')
  const globalOptions = filterHelp(end === -1 ? options : options.slice(0, end))
  const everyCommand = new Set(globalOptions.split('\n').flatMap((line) => OPTION_LINE.exec(line)?.[1] ?? []))
  const sections = commands.map(({ command, help }) => {
    const left = new Set([...everyCommand, ...(REFUSED_FLAGS[command] ?? [])])
    const own = filterHelp(help).split('\n').filter((line) => !left.has(OPTION_LINE.exec(line)?.[1] ?? ''))
    return `## ${command}\n\n\`\`\`\n${own.join('\n')}\n\`\`\`\n`
  }).join('\n')
  return `${versionStamp(version)}
# Command Flags

Each command's \`--help\`, as agent-desktop ${version} prints it, without the
flags the app sets itself or refuses. A command's own section leaves out the
options every command takes, listed first.

## Options for every command

\`\`\`
${globalOptions}
\`\`\`

${sections}`
}

