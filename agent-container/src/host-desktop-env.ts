import * as fs from 'fs'

/**
 * Whether agents get computer use and host scripts: the tools that act on the
 * desktop of the host's machine. The host answers in HOST_COMPUTER_USE. A host
 * older than that answer offered both on macOS and Windows.
 */
export function isComputerUseHost(): boolean {
  const answer = process.env.HOST_COMPUTER_USE
  return answer === undefined ? ['darwin', 'win32'].includes(process.env.HOST_PLATFORM || '') : answer === 'true'
}

/**
 * The host's desktop OS as computer use meets it: its name, and agent-desktop's
 * guide for it (headless and headed delivery differ by OS). Null when the host
 * is neither macOS nor Windows.
 */
export function computerUseHostOs(): { name: string; guide: string; platform: 'macos' | 'windows' } | null {
  switch (process.env.HOST_PLATFORM) {
    case 'darwin': return { name: 'macOS', guide: '/opt/gamut/docs/computer-use/macos.md', platform: 'macos' }
    case 'win32': return { name: 'Windows', guide: '/opt/gamut/docs/computer-use/windows.md', platform: 'windows' }
    default: return null
  }
}

/** A line for a computer-use prompt naming the host's OS and its guide, or '' when unknown. */
export function computerUseHostLine(): string {
  const os = computerUseHostOs()
  return os ? `The user's computer runs ${os.name}; agent-desktop's guide for it is \`${os.guide}\`.` : ''
}

/** The main computer-use guide: the Gamut header and agent-desktop's own core guide. */
export const COMPUTER_USE_GUIDE = '/opt/gamut/docs/computer-use.md'

/**
 * agent-desktop's guides as the computer-use agent's prompt carries them: the
 * main guide, then the host OS's. Each is read from the image; one the image
 * does not ship (a run outside it) is left out.
 */
export function computerUseGuides(read: (file: string) => string = (file) => fs.readFileSync(file, 'utf8')): string {
  const files = [COMPUTER_USE_GUIDE, computerUseHostOs()?.guide].filter((file): file is string => Boolean(file))
  return files.flatMap((file) => {
    try {
      // The generator's stamp is for whoever edits the files, not the agent.
      return [read(file).replace(/^<!-- generated by .* -->\n/gm, '').trim()]
    } catch {
      return []
    }
  }).join('\n\n')
}

/** Whether the host is the Mac App Store edition, whose App Sandbox leaves out what reaches outside the app. */
export function isAppSandboxHost(): boolean {
  return process.env.HOST_APP_SANDBOX === 'true'
}
